/**
 * Regenerate src/bundled-mod-index.ts from docs/mod-index.json (the
 * canonical, GitHub-hosted copy). Run after editing the json:
 *   node scripts/gen-mod-index.mjs
 * The generated module ships inside the backend bundle so the Mod 库 page
 * still works when every mirror is unreachable (offline / GFW flake).
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const jsonPath = path.join(root, "docs", "mod-index.json");
const outPath = path.join(root, "src", "bundled-mod-index.ts");

const doc = JSON.parse(readFileSync(jsonPath, "utf8"));
const banner = `/**
 * GENERATED by scripts/gen-mod-index.mjs from docs/mod-index.json — do not
 * edit by hand. Edit the json, then re-run the script. This embedded copy is
 * the offline fallback for d2r:modIndexList when every mirror fails.
 */
export const BUNDLED_INDEX_FETCHED_AT = ${JSON.stringify(doc.updatedAt)};

export const BUNDLED_MOD_INDEX = ${JSON.stringify(doc, null, 2)} as const;
`;
writeFileSync(outPath, banner, "utf8");
console.log(`wrote ${path.relative(root, outPath)} (${doc.entries.length} entries)`);
